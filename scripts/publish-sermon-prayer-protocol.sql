<h3>To all Kingdom Family,</h3>

Grace and peace to you all!

We had a powerful, fruitful, and deeply revelatory session today as we continued our series on The Keys of the Kingdom.

Today’s focus was on Prayer, with special emphasis on <strong>The Prayer Protocol in the Court of Heaven</strong>, using King Jehoshaphat’s prayer as our main biblical model.

The session opened with a recap of previous lessons and moved into a detailed study of how we can present our petitions effectively before God.

We discovered that prayer is not just casual talking — it is a legal and relational protocol in the Court of Heaven.

We used <strong>2 Chronicles 20:1-25</strong> as the central passage and broke it down step by step:

<h4>King Jehoshaphat’s Prayer Protocol (2 Chronicles 20)</h4>

<strong>1. Seeking God First (v.3-4)</strong>
Jehoshaphat resolved to inquire of the Lord and called the whole nation to fast and seek God.

<strong>2. Praising and Acknowledging God (v.6)</strong>
“Lord, the God of our ancestors, are you not the God who is in heaven? You rule over all the kingdoms of the nations. Power and might are in your hand, and no one can withstand you.”

<strong>3. Reminding God of His Past Faithfulness (v.7-9)</strong>
He recalled God’s covenant with Abraham and previous deliverances.

<strong>4. Clearly Presenting the Problem (v.10-11)</strong>
He described the invading armies and the threat to the inheritance God had given them.

<strong>5. Making the Specific Petition / Request for Judgment (v.12)</strong>
“Our God, will you not judge them? For we have no power to face this vast army that is attacking us. We do not know what to do, but our eyes are on you.”

<strong>6. Listening for God’s Verdict (v.14-17)</strong>
The Spirit of the Lord came upon Jahaziel, and God gave a clear verdict: “Do not be afraid or discouraged because of this vast army. For the battle is not yours, but God’s… You will not have to fight this battle. Take up your positions; stand firm and see the deliverance the Lord will give you.”

<strong>7. Worship, Faith, and Obedience (v.18-22)</strong>
They bowed down in worship, praised God in advance, and went out to the battlefield with singing. God then caused the enemy armies to turn against each other.

<h4>Highlights from the Discussion</h4>

• Everyone was amazed by this fresh revelation of the Kingdom Prayer Protocol. Members shared powerful testimonies about how their prayers have changed when they approached God with this understanding.
• Many realized they had been begging instead of presenting their cases with faith and confidence.
• The discussion emphasized that this is not a new doctrine, but a practical pattern seen in successful prayers throughout the Bible (Jehoshaphat, Hezekiah, Nehemiah, Daniel, etc.). It was noted that treating the Bible as the Kingdom Constitution rather than just a religious book gives us deeper insight into how God’s government operates.
• A key point raised and clarified: Even though God is sovereign, He has given us authority on earth (Genesis 1:26-28). Prayer is the legal means through which we release His will on earth.

<h4>Commitments from Today</h4>

• To readjust our personal prayer style using the Court of Heaven protocol.
• To approach God with reverence, present problems clearly, and trust Him fully.
• To maintain an attitude of worship and faith even before seeing the answer.

The session ended with great joy, lifted faith, and fresh determination to pray more effectively.

<h4>Administrative Notes</h4>

• We also had a brief update on the development of the new Kingdom Family website. It will serve as a central platform to archive teachings, connect members, and make lessons easily accessible for future reference.
• Newcomers were warmly welcomed, and we discussed refining the platform name. For now, it was agreed to use “Kingdom Citizens” as the working name and the domain The Kingdom Citizens which make it welcoming and easy to communicate.

<strong>Next Week:</strong>
We will meet again at the same time to continue with another powerful Key of the Kingdom.

<strong>Memory Verse for This Week:</strong>
“We do not know what to do, but our eyes are on you.” (2 Chronicles 20:12)

Thank you all for your hunger, participation, and honesty today. This revelation on the Prayer Protocol is truly life-changing. Let us put it into practice this week and expect God to move powerfully in our lives.

See you next Saturday!

Blessings and love,
