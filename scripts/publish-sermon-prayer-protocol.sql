<h3>ለእግዚአብሔር መንግሥት ቤተሰቦች በሙሉ፤</h3>

ጸጋና ሰላም ለሁላችሁ ይሁን!

«የመንግሥተ ሰማያት ቁልፎች» (The Keys of the Kingdom) በሚለው ተከታታይ ትምህርታችን ላይ በዛሬው ዕለት እጅግ ኃይለኛ፣ ፍሬያማ እና ጥልቅ መገለጥ የበዛበት ጊዜ ነበረን።

የዛሬው ትኩረታችን በጸሎት ላይ የነበረ ሲሆን፣ በተለይም በንጉሥ ኢዮሣፍጥ ጸሎት ላይ የተመሠረተውን <strong>በሰማያዊው ችሎት ፊት የሚቀርበውን የጸሎት ሥርዓት (The Prayer Protocol in the Court of Heaven)</strong> ዋና የመጽሐፍ ቅዱስ አምሳያችን በማድረግ ተመልክተናል።

ስብሰባው የተጀመረው ባለፉት ክፍለ-ጊዜዎች የተማርናቸውን ትምህርቶች በመከለስ ሲሆን፣ በመቀጥምም ልመናችንን በእግዚአብሔር ፊት እንዴት በብቃት ማቅረብ እንደምንችል ወደሚያሳየው ዝርዝር ጥናት ተሻገርን።

<strong>ጸሎት እንዲሁ ተራ ጨዋታ ሳይሆን፣ በሰማያዊው ችሎት ፊት የሚደረግ ሕጋዊና ግንኙነታዊ ሥርዓት (Protocol) መሆኑን ተረድተናል።</strong>

2 ዜና መዋዕል 20:1-25ን እንደ ዋና ጥቅስ በመጠቀም፣ ደረጃ በደረጃ እንደሚከተለው ከፋፍለን አጥንተነዋል፦

<h4>የንጉሥ ኢዮሣፍጥ የጸሎት ሥርዓት (2 ዜና 20)</h4>

<strong>1. እግዚአብሔርን ማስቀደም (ቁ. 3-4)</strong>
ኢዮሣፍጥ እግዚአብሔርን ለመፈለግ ፊቱን አቅና፤ መላውም ሕዝብ እንዲጾምና እግዚአብሔርን እንዲፈልግ አወጀ።

<strong>2. እግዚአብሔርን ማመስገንና ማክበር (ቁ. 6)</strong>
«አቤቱ የአባቶቻችን አምላክ ሆይ፥ አንተ በሰማይ የምትኖር አምላክ አይደለህም? አንተስ በአሕዛብ መንግሥታት ሁሉ ላይ የምትገዛ አይደለህም? ማንም ይቃወምህ ዘንድ የማይችል ኃይልና ሥልጣን በእጅህ ነው!»

<strong>3. የእግዚአብሔርን ያለፈ ታማኝነት ማስታወስ (ቁ. 7-9)</strong>
እግዚአብሔር ከአብርሃም ጋር ያደረገውን ኪዳን እና ቀደም ሲል ያደረገውን ታላቅ ማዳን አስታወሰ።

<strong>4. ችግሩን በግልጽ ማቅረብ (ቁ. 10-11)</strong>
ሊወሯቸው የመጡትን ሰራዊቶች እና እግዚአብሔር ለሰጣቸው ርስት እንዴት ስጋት እንደሆኑ ገለጸ።

<strong>5. የተለየ ልመና / የፍርድ ጥያቄ ማቅረብ (ቁ. 12)</strong>
«አምላካችን ሆይ፥ አትፈርድባቸውምን? ይህን የመጣብንን ታላቅ ወገን እንቃወም ዘንድ አቅም የለንምና፥ የምናደርገውንም አናውቅምና፤ ነገር ግን ዓይኖቻችን ወደ አንተ ናቸው።»

<strong>6. የእግዚአብሔርን ውሳኔ (ፍርድ) ማዳመጥ (ቁ. 14-17)</strong>
የእግዚአብሔር መንፈስ በያሕዜል ላይ መጣ፥ እግዚአብሔርም ግልጽ ውሳኔ ሰጠ፦ «ከዚህ ከታላቁ ወገን የተነሣ አትፍሩ፥ አትደንግጡም፤ ሰልፉ የእግዚአብሔር ነው እንጂ የእናንተ አይደለም... በዚህ ሰልፍ የምትዋጉ አይደላችሁም፤ ተሰለፉ፥ ዝም ብላችሁም ቁሙ፥ የእግዚአብሔርንም ማዳን ከእናንተ ጋር እዩ።»

<strong>7. አምልኮ፣ እምነት እና ታዛዥነት (ቁ. 18-22)</strong>
በግምባራቸው ተደፍተው ሰገዱ፣ መልሱ ከመምጣቱ በፊት እግዚአብሔርን በቅድሚያ አመሰገኑ፣ እየዘመሩም ወደ ውጊያው መስክ ወጡ። ከዚያም እግዚአብሔር ጠላቶቻቸው እርስ በርሳቸው እንዲጠፋፉ አደረገ።

<h4>ከውይይቱ የተገኙ ዋና ዋና ነጥቦች</h4>

• ሁሉም ሰው ስለዚህ አዲስ የመንግሥተ ሰማያት የጸሎት ሥርዓት መገለጥ እጅግ ተደንቋል። አባላት ይህንን ግንዛቤ ይዘው ወደ እግዚአብሔር መቅረብ ከጀመሩ ወዲህ ጸሎታቸው እንዴት እንደተቀየረ ኃይለኛ ምስክርነቶችን አካፍለዋል።
• <strong>ብዙዎች በእምነትና በመተማመን ጉዳያቸውን ከማቅረብ ይልቅ፣ ሲለምኑ (ሲማጸኑ) እንደነበር ተገንዝበዋል።</strong>
• ውይይቱ ይህ አዲስ አስተምህሮ ሳይሆን፣ በመጽሐፍ ቅዱስ ውስጥ ስኬታማ በነበሩ ጸሎቶች ሁሉ (እንደ ኢዮሣፍጥ፣ ሕዝቅያስ፣ ነህምያ፣ ዳንኤል፣ ወዘተ) ላይ የታየ ተግባራዊ ምሳሌ መሆኑን አጽንዖት ሰጥቶታል። መጽሐፍ ቅዱስን እንደ አንድ ሃይማኖታዊ መጽሐፍ ብቻ ሳይሆን፣ እንደ <strong>«የመንግሥቱ ሕገ-መንግሥት»</strong> አድርጎ ማየት የእግዚአብሔር መንግሥት እንዴት እንደሚሠራ ጥልቅ ግንዛቤ እንደሚሰጠን ተገልጿል።
• የተነሳና ግልጽ የተደረገ ዋና ነጥብ፦ እግዚአብሔር ሉዓላዊ ቢሆንም፣ በምድር ላይ ሥልጣንን ለእኛ ሰጥቶናል (ዘፍጥረት 1:26-28)። ጸሎት የእርሱን ፈቃድ በምድር ላይ ለመልቀቅ የምንጠቀምበት ሕጋዊ መንገድ ነው።

<h4>ከዛሬው ዕለት የገባናቸው ቃል ኪዳኖች</h4>

• የግል የጸሎት ሕይወታችንን በሰማያዊው ችሎት ሥርዓት መሠረት ማስተካከል።
• ወደ እግዚአብሔር በክብር መቅረብ፣ ችግሮቻችንን በግልጽ ማቅረብ እና በእርሱ ሙሉ በሙሉ መታመን።
• መልሱን ገና በአካል ሳናይ እንኳ፣ የአምልኮ እና የእምነት አቋምን ጠብቆ መቀጠል።

ስብሰባው በታላቅ ደስታ፣ ባደገ እምነት እና በበለጠ ብቃት ለመጸለይ በታደሰ ቁርጠኝነት ተጠናቋል።

<h4>አስተዳደራዊ ማስታወሻዎች</h4>

• ስለ አዲሱ የ«ኪንግደም ፋሚሊ» (Kingdom Family) ድረ-ገጽ ግንባታ አጭር መረጃ ተሰጥቷል። ይህ ድረ-ገጽ ትምህርቶችን ለማስቀመጥ፣ አባላትን ለማገናኘትና ለወደፊት ማጣቀሻ የሚሆኑ ትምህርቶችን በቀላሉ ለማግኘት እንደ ማዕከላዊ መድረክ ያገለግላል።
• ለአዲስ ወደዚህ ቻናል ለገቡ ሰዎች ሞቅ ያለ አቀባበል የተደረገላቸው ሲሆን፣ የመድረኩን ስም ስለማሻሻልም ተወያይተናል። ለጊዜው <strong>«Kingdom Citizens» (የመንግሥቱ ዜጎች)</strong> የሚለውን ስም እንደ ጊዜያዊ ስም ለመጠቀምና The Kingdom Citizens የሚለውን ድረ-ገጽ (domain) ለመጠቀም ተስማምተናል፤ ይህም ተደራሽ እና በቀላሉ የሚግባቡበት ያደርገዋል።

<strong>ለሚቀጥለው ሳምንት፦</strong>
በሚቀጥለው ቅዳሜ በተመሳሳይ ሰዓት ሌላ «የመንግሥቱ ቁልፍ» ሀሳብ ይዘን እንገናኛለን።

<strong>የዚህ ሳምንት ምናሰላስለዉ ጥቅስ፦</strong>
«የምናደርገውንም አናውቅምና፤ ነገር ግን ዓይኖቻችን ወደ አንተ ናቸው።» (2 ዜና መዋዕል 20:12)

ዛሬ ላሳያችሁት መንፈሳዊ ረሃብ፣ ተሳትፎ እና ቅንነት ሁላችሁንም አመሰግናለሁ። ይህ ስለ ጸሎት ሥርዓት የተገለጠው መገለጥ በእውነት ሕይወት የሚለውጥ ነው። በዚህ ሳምንት በተግባር እንተርጉመው፣ እግዚአብሔርም በሕይወታችን ውስጥ በኃይል እንዲሠራ እንጠብቅ።

የሚቀጥለው ቅዳሜ እንገናኝ!

