<h3>ለሁላችሁም የመንግሥቱ ቤተሰቦች፣</h3>

ጸጋና ሰላም ለሁላችሁ ይሁን!

ለዛሬው ፍሬያማ የመንግሥቱ ትምህርት ጊዜ በድጋሚ አመሰግናለሁ! 🙌

እንደተለመደው፣ "የመንግሥቱ ቁልፎች – በዚህ የአሁኑ መንግሥት ውስጥ እንዴት መኖር ይቻላል?" በሚለው ተከታታይ ትምህርታችን ቀጥለናል።

መጀመሪያ፣ ባለፈው ሳምንት እምነት የመንግሥቱ መንፈሳዊ ገንዘብ (Currency) ስለመሆኑ የተማርነውን ከለስ አድርገናል። ይህም፦

• አነስተኛ እምነት ወደ ትግል እንደሚመራ፣
• ታላቅ እምነት ደግሞ ተአምራትን እንደሚለቅ፣
• እንዲሁም እምነት የእግዚአብሔርን ቃል በመስማት እንደሚመጣ (ሮሜ 10:17) ተመልክተናል።

ዛሬ ደግሞ በሦስተኛው ቁልፍ — በእምነት — ሁለት አስፈላጊ ነጥቦች ላይ ጠለቅ ብለን ተወያይተናል፦

<strong>1. የእምነት ዓላማ (መደገፊያ)</strong>

እምነታችን መደረግ ያለበት በእግዚአብሔር ላይ ብቻ እንጂ በሰዎች፣ በገንዘብ፣ በሁኔታዎች ወይም በራሳችን ላይ መሆን እንደሌለበት አጽንኦት ሰጥተናል።

• "በእግዚአብሔር እመኑ" (ማርቆስ 11:22)
• "በፍጹም ልብህ በእግዚአብሔር ታመን፥ በራስህም ማስተዋል አትደገፍ" (ምሳሌ 3:5-6)
• "ያለ እምነትም ደስ ማሰኘት አይቻልም፤ ወደ እግዚአብሔር የሚደርስ እግዚአብሔር እንዳለ ለሚፈልጉትም ዋጋ እንደሚሰጥ ያምን ዘንድ ያስፈልገዋልና" (ዕብራውያን 11:6)
• "በእግዚአብሔር እመኑ፥ በእኔም ደግሞ እመኑ" (ዮሐንስ 14:1)

እውነተኛ እምነት ጠንካራ የሚሆነው፣ መደገፊያው የታመነና ሁሉን ቻይ የሆነው አምላክ ስለሆነ ነው።

<strong>2. የእምነት ጥቅሞች – ደኅንነት እና እስከ ኢየሱስ መመለስ ድረስ መመላለስ</strong>

ትልቁ የእምነት ጥቅም ደኅንነትና የዘላለም ሕይወት ሲሆን፣ ይህም በጸጋ በእምነት የምንቀበለው እንጂ በሥራ አይደለም።

• "ጸጋው በእምነት አድኖአችኋልና፤ ይህም የእግዚአብሔር ስጦታ ነው እንጂ ከእናንተ አይደለም" (ኤፌሶን 2:8-9)
• "በእርሱ የሚያምን ሁሉ የዘላለም ሕይወት እንዲኖረው እንጂ እንዳይጠፋ እግዚአብሔር አንድያ ልጁን እስኪሰጥ ድረስ ዓለሙን እንዲሁ ወዶአልና" (ዮሐንስ 3:16)
• "ቃሌን የሚሰማ የላከኝንም የሚያምን የዘላለም ሕይወት አለው" (ዮሐንስ 5:24)

ሌሎች ጥቅሞች ደግሞ ፈውስን ("ልጄ ሆይ፥ እምነትሽ አድኖሻል" – ማቴዎስ 9:22)፣ ነጻ መውጣትን፣ የዕለት ተዕለት በረከቶችን እና ኢየሱስ ምድራዊ መንግሥቱን ለመመሥረት እስኪመለስ ድረስ በታማኝነት ለመመላለስ የሚያስችል ጥንካሬን ያካትታሉ።

በእይታ ሳይሆን በእምነት እንድንኖር ተጠርተናል (2 ቆሮንቶስ 5:7)፤ ይህም የእምነታችን ራስና ፈጻሚ የሆነውን ኢየሱስን በመመልከት ነው (ዕብራውያን 12:2)።

ውይይታችን በጣም ፍሬያማና አበረታች ነበር። እያንዳንዱ ሰው በንቃት በመሳተፍ፣ በእምነት ማደግ በሚያስፈልጋቸው ነጥቦች ላይ የራሳቸውን አመለካከት፣ ምስክርነትና የግል ተሞክሮ አካፍለዋል። ከእያንዳንዱ ሰው መስማት ትልቅ በረከት ነበር!

በመጨረሻም፣ በሚቀጥለው ሳምንት በዚሁ ቁልፍ — በእምነት — ለመቀጠል ተስማምተናል። ርዕሱም "የእምነት ጠላቶች እና በዕለት ተዕለት ሕይወታችን እንዴት እንተገብረዋለን?" የሚል ይሆናል። እምነትን የሚያውኩ ነገሮችንና እነርሱን የምናሸንፍባቸውን ተግባራዊ መንገዶች እንመለከታለን።

<strong>የሳምንቱ የቃል ጥናት ጥቅስ፦</strong>

"ጸጋው በእምነት አድኖአችኋልና፤ ይህም የእግዚአብሔር ስጦታ ነው እንጂ ከእናንተ አይደለም።" (ኤፌሶን 2:8)

ለልባችሁ ግልጽነትና ለንቁ ተሳትፎአችሁ በድጋሚ አመሰግናለሁ።

በዚህ ሳምንት በታላቅ እምነት ማደጋችንን እንቀጥል፣ የተማርነውንም በተግባር ላይ እናውል።
የእምነትን ቁልፍ ማሰስ ለመቀጠል በሚቀጥለው ቅዳሜ እንገናኝ!

በረከትና ፍቅር ይብዛላችሁ።
