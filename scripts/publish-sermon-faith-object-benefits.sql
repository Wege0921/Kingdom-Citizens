<h3>To all Kingdom Family,</h3>

Grace and peace to you all!

Thank you for another powerful and fruitful Kingdom teaching session today! 🙌

As usual, we continued our series on The Keys of the Kingdom – How to Live in This NOW Kingdom.

We first recapped last week’s teaching on Faith as the spiritual currency of the Kingdom — how little faith leads to struggle, while great faith releases miracles, and how faith comes by hearing the Word of God (Romans 10:17).

Today we went deeper into two important aspects of the third key — Faith:

<strong>1. The Object of Faith</strong>

We emphasized that our faith must be placed in God alone, not in people, money, circumstances, or ourselves.

• "Have faith in God" (Mark 11:22)
• "Trust in the Lord with all your heart and lean not on your own understanding" (Proverbs 3:5-6)
• "Without faith it is impossible to please God, because anyone who comes to him must believe that he exists and that he rewards those who earnestly seek him" (Hebrews 11:6)
• "You believe in God; believe also in me" (John 14:1)

True faith is strong because its object is the faithful, all-powerful God.

<strong>2. The Benefits of Faith – Salvation and Walking Until Jesus Returns</strong>

The greatest benefit of faith is salvation and eternal life, which we receive by grace through faith, not by works.

• "For it is by grace you have been saved, through faith — and this is not from yourselves, it is the gift of God" (Ephesians 2:8-9)
• "For God so loved the world that he gave his one and only Son, that whoever believes in him shall not perish but have eternal life" (John 3:16)
• "Whoever hears my word and believes him who sent me has eternal life" (John 5:24)

Other benefits include healing ("Daughter, your faith has healed you" – Matthew 9:22), deliverance, daily blessings, and the strength to walk faithfully until Jesus returns to establish His physical Kingdom on earth.

We are called to live by faith, not by sight (2 Corinthians 5:7), keeping our eyes on Jesus, the author and perfecter of our faith (Hebrews 12:2), until He comes back.

The discussion was very fruitful and encouraging. Everyone participated actively, sharing their views, testimonies, and personal experiences on where they need to grow in faith. It was a real blessing to hear from each person!

Finally, we all agreed to continue with the same key — Faith next week. The topic will be "Enemies of Faith and How to Apply This in Our Real Life." We will look at what hinders faith and practical ways to overcome them so we can walk in stronger faith daily.

<strong>Memory Verse for the Week:</strong>
"For it is by grace you have been saved, through faith — and this is not from yourselves, it is the gift of God." (Ephesians 2:8)

Thank you once again for your open hearts and active participation. Let’s keep growing in great faith this week and put into practice what we learned.

See you next Saturday as we continue exploring the Key of Faith!

Blessings and love,
