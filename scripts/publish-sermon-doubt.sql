<h3>የመንግሥቱ ቤተሰቦች (Kingdom Family)</h3>

ለኪንግደም ፋሚሊ በሙሉ፤
የእግዚአብሔር ጸጋና ሰላም ለሁላችሁ ይሁን!

ለዛሬው እጅግ አስደናቂና ኃይለኛ ክፍለ-ጊዜ እግዚአብሔር ይመስገን! 🙌 መንፈስ ቅዱስ በእውነት በመካከላችን ነበረ፤ ሁሉም ሰው በደስታ፣ በክፍት ልብ፣ በጥልቅ ግንዛቤዎችና በሚያበረታቱ ምስክሮች ተሳትፏል። ንቁ ተሳትፎ ስላደረጋችሁ ሁላችሁንም አመሰግናለሁ።

<strong>የዛሬው ክፍለ-ጊዜ ማጠቃለያ</strong>

ባለፉት ሳምንታት ስለ መንግሥቱ ቁልፎች የተማርናቸውን ትምህርቶች በመከለስ የ ጀመርን ሲሆን እግዚአብሔር ለሰው ልጅ ያለውን ዘላለማዊ ዕቅድ ራሳችንን ከለስን ፦

• ከመጀመሪያው ጀምሮ፣ እግዚአብሔር ሰውን በመልኩና በአምሳሉ የፈጠረው እንዲገዛና ስልጣን እንዲኖረው ነው (ዘፍጥረት 1:26-28).
• በኤደን ገነት ሰው በመውደቁ ምክንያት፣ የሰው ልጅ ያንን ስልጣን አጣ።
• ነገር ግን እግዚአብሔር በታላቅ ምሕረቱ እኛን ለመዋጀት ልጁን ኢየሱስ ክርስቶስን ላከ።
• ከዚያ ጊዜ ጀምሮ፣ ላለፉት 2,000 ዓመታት፣ ኢየሱስ የእግዚአብሔር መንግሥት መምጣቱን ሲያውጅ አኛም አየኖርንበት ቆይቷል።
• አሁን የምንገኘው "ተጀምሮ ባልተጠናቀቀ" (already but not yet) ምዕራፍ ውስጥ ነው — በአዲስ ልደት ወደ መንግሥቱ ገብተናል፤ ነገር ግን ጌታችን ኢየሱስ ክርስቶስ በክብር ተመልሶ የ1,000 ዓመት ግዛቱን በምድር ላይ ሲመሰርት፣ በመጨረሻም የዚህ ዘመን ፍጻሜ ሆኖ አዲስ ሰማይና አዲስ ምድር ሲሆን የሚሆነውን ሙሉ መገለጥ እየጠበቅን ነው።

ከዚህ ሰፊ ክለሳ በኋላ፣ በሦስተኛው የመንግሥቱ ቁልፍ — እምነት — ላይ ጥልቅ ጥናታችንን ቀጠልን፤ በተለይም "ጥርጣሬ የእምነት ጠላት" በሚለው ነጥብ ላይ አተኮርን።

<strong>ዋና ትምህርት፡ ጥርጣሬ – የእምነት ጠላት</strong>

ጥርጣሬ ከእምነት ትልልቅ ጠላቶች አንዱ መሆኑን ተምረናል። መንፈሳዊ አቅማችንን ያዳክማል እንዲሁም እግዚአብሔር የሰጠንን ተስፋ እንዳንቀበል እንቅፋት ይሆናል።

<strong>ያጠናናቸው ቁልፍ ጥቅሶች፦</strong>

<strong>ያዕቆብ 1:5-8</strong>
"ነገር ግን በምንም ሳይጠራጠር በእምነት ይለምን፤ የሚጠራጠር ሰው በነፋስ የሚገፋና የሚታወክ የባሕርን ማዕበል ይመስላልና . . . ሁለት አሳብ ላለው በመንገዱም ሁሉ ለሚወላውል ለዚያ ሰው ከጌታ ዘንድ አንዳች እንዲቀበል አይምሰለው።"

<strong>ማቴዎስ 14:30-31 (ጴጥሮስ በውሃ ላይ ሲራመድ)</strong>
ጴጥሮስ ነፋሱን አይቶ መስጠም ሲጀምር፣ ኢየሱስ "አንተ እምነት የጎደለህ፥ ስለ ምን ተጠራጠርህ?" አለው።

<strong>ማቴዎስ 21:21-22 (የበለሷ ዛፍ)</strong>
"እውነት እላችኋለሁ፥ እምነት ቢኖራችሁ ባትጠራጠሩም . . . ይህን ተራራ እንኳ፦ ተነቅለህ ወደ ባሕር ተወርወር ብትሉት ይሆናል፤ አምናችሁም በጸሎት የምትለምኑትን ሁሉ ትቀበላላችሁ።"

<strong>ሮሜ 14:23</strong>
"የሚጠራጠር ግን ቢበላ በእምነት ስላልሆነ ተፈርዶበታል፤ በእምነትም ያልሆነ ሁሉ ኃጢአት ነው።"

<strong>ከዛሬው ውይይት የተገኙ ጠቃሚ ትምህርቶች</strong>

በውይይታችን አማካኝነት እነዚህን አስፈላጊ እውነቶች ተረድተናል፦

• እየተጠራጠርን ስንጸልይ የለመነውን አንቀበልም (ያዕቆብ 1:6-7).
• አንዴ በእምነት መራመድ ከጀመርን በኋላ፣ በዙሪያችን ያሉትን ሁኔታዎች ወይም ማዕበሎች ማየት የለብንም — ዓይናችንን በኢየሱስ ላይ ማድረግ አለብን (ማቴዎስ 14:30-31).
• ያለ ጥርጣሬ እምነት ካለን፣ ሕይወት ያላቸውን ነገሮች (እንደ በለሷ ዛፍ) እና ሕይወት የሌላቸውን ነገሮች (እንደ ተራራዎች) ማንቀሳቀስ እንችላለን። ለሚያምን ሁሉ የማይቻል ነገር የለም (ማቴዎስ 17:20፣ ማርቆስ 9:23).
• እንደ መብላት ባሉ የዕለት ተዕለት ነገሮች እንኳ ሳይቀር፣ በጥርጣሬና በኰነነ ሕሊና ካደረግነው ኃጢአት ይሆንብናል (ሮሜ 14:23).

ሁሉም ሰው እጅግ ታንጿል እንዲሁም ተበረታትቷል። ብዙዎች ዛሬ እምነታቸው እንዴት እንደጠነከረ አካፍለዋል። አንዳንድ የቴክኒክ ችግሮች (የኔትወርክ መቆራረጥና የመብራት መጥፋት) ቢኖሩም፣ ፕሮግራሙን በድል አጠናቅቀናል፤ የዕለቱንም ዋና መልዕክት በግልጽ ተረድተናል።

<strong>የሚቀጥለው ሳምንት ርዕስ፦</strong>
በዚሁ ቁልፍ (እምነት) ለመቀጠል ወይም ወደ ሌላኛው ኃይለኛ የመንግሥቱ ቁልፍ ማለትም "ጸሎትና የቃሉ ኃይል" ወደሚለው ለመሻገር ተስማምተናል።

<strong>የሳምንቱ የቃል ጥናት ጥቅስ፦</strong>
"ነገር ግን በምንም ሳይጠራጠር በእምነት ይለምን . . ." (ያዕቆብ 1:6)

በዚህ ሳምንት የተማርነውን በተግባር እንዋል — ሳንጠራጠር እንጸልይ፣ በእምነት እንጂ በማየት አንመላለስ፣ በሁሉም የሕይወታችን ዘርፍ እግዚአብሔርን ሙሉ በሙሉ እንታመን።

ስለ ደስ የሚል ተሳትፏችሁ ደግሜ አመሰግናለሁ።

እግዚአብሔር በመካከላችን ጥልቅ ሥራ እየሰራ ነው!

የሚቀጥለው ቅዳሜ እንገናኝ!

