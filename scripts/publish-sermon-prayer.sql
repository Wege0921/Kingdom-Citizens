<h3>የዛሬው ስብሰባ ማጠቃለያ</h3>

ለእግዚአብሔር መንግሥት ቤተሰቦች በሙሉ፣

ጸጋና ሰላም ለሁላችሁ ይሁን!

ስለ «የመንግሥተ ሰማያት መክፈቻዎች» (The Keys of the Kingdom) የጀመርነውን ተከታታይ ትምህርት በመቀጠል፣ ዛሬም ሌላ ድንቅ፣ ኃያል እና እጅግ ፍሬያማ የሆነ ጊዜ ነበረን።

የዛሬው ትኩረታችን እጅግ ኃያል ከሆኑት መክፈቻዎች አንዱ በሆነው ላይ ነበረ፤ እርሱም፦ <strong>ጸሎት</strong> ነው።

<strong>የዛሬው ትምህርት ማጠቃለያ</strong>

የጀመርነው የጸሎትን ትርጉም በመመርመር ነበር። ጸሎት ማለት ዝም ብሎ እግዚአብሔርን ነገሮችን መለመን ብቻ አይደለም፤ ከሰማያዊ አባታችን ጋር የምናደርገው የሐሳብ ልውውጥ (ኮሙኒኬሽን) እና ጥልቅ የቅርብ ግንኙነት ነው — እርሱን ማነጋገር፣ እርሱን ማዳመጥ እና ፈቃዳችንን ከእርሱ ፈቃድ ጋር ማሰለፍ (ማስማማት) ማለት ነው።

በመቀጠልም የጸሎትን መጀመሪያ (ምንጭ) በመፈለግ እግዚአብሔር ከአዳም ጋር ወደተመላለሰበትና ወደተገናኘበት ወደ ኤደን ገነት ተመለስን፦

<strong>ዘፍጥረት 3:8-9</strong>
«ቀኑ መስተንፈሻ ሲል፣ የእግዚአብሔር አምላክን ድምፅ በገነት ውስጥ ሲመላለስ ሰሙ፤ አዳምና ሚስቱም ከእግዚአብሔር አምላክ ፊት በገነት ዛፎች መካከል ተሸሸጉ። እግዚአብሔር አምላክም አዳምን ጠርቶ፣ “የት ነህ?” አለው።»

<strong>ለምን እንደምንጸልይም ተወያይተናል፦</strong>

• ከእግዚአብሔር ጋር ያለንን ግንኙነት ለመገንባትና ለመጠበቅ
• የእግዚአብሔርን መንግሥት በምድር ላይ ለማስፋፋት («መንግሥትህ ትምጣ፤ ፈቃድህ በሰማይ እንደ ሆነች እንዲሁ በምድር ትሁን» – ማቴዎስ 6:10)
• ኃይልን፣ መመሪያን፣ አቅርቦትን (አስፈላጊ ነገሮችን) እና መልሶችን ለመቀበል
• እግዚአብሔር በምድር ላይ የሰጠንን ሥልጣን ለመለማመድ (ለመጠቀም)

እንዲሁም የተለያዩ የጸሎት ዓይነቶችን ተመልክተናል፦ ልመና፣ ምስጋና፣ ምልጃ፣ የስምምነት ጸሎት፣ የእምነት ጸሎት፣ እና የውዳሴና የአምልኮ ጸሎት።

<strong>በሰማይ ፍርድ ቤት ስላለው የጸሎት/የልመና ሥነ-ሥርዓት (Protocol)</strong>

ጸሎት ማለት በመንፈሳዊ ፍርድ ቤት ፊት ጉዳይን እንደ ማቅረብ መሆኑን ተምረናል። በዚያም ውስጥ የእያንዳንዱ አካል ድርሻ እንደሚከተለው ነው፦

<strong>እግዚአብሔር – ጻድቁ ፈራጅ እና ንጉሥ</strong>
ዕብራውያን 4:16
«እንግዲህ ምሕረትን እንድንቀበል በሚያስፈልገንም ጊዜ የሚረዳንን ጸጋ እንድናገኝ፣ ወደ ጸጋው ዙፋን በደፍረት እንቅረብ።»

<strong>ኢየሱስ – ጠበቃችን (የመከላከያ ጠበቃ) እና ሊቀ ካህናችን</strong>
1 ዮሐንስ 2:1
«ማንም ኃጢአትን ቢያደርግ ከአብ ዘንድ ጠበቃ አለን፥ እርሱም ጻድቅ የሆነው ኢየሱስ ክርስቶስ ነው።»

<strong>መንፈስ ቅዱስ – ረዳታችንና አማላጃችን</strong>
ሮሜ 8:26-27
«እንዲሁም ደግሞ መንፈስ ድካማችንን ያግዛል፤ እንዴት እንድንጸልይ እንደሚገባን አናውቅምና፥ ነገር ግን መንፈስ ራሱ በማይነገር መቃተት ይማልድልናል፤ ልብንም የሚመረምረው የመንፈስ ሐሳብ ምን እንደ ሆነ ያውቃል፥ እንደ እግዚአብሔር ፈቃድ ቅዱሳንን ይማልዳልና።»

<strong>ሰይጣን – ከሳሽ / ዓቃቢ ሕግ</strong>
ራእይ 12:10
«...በአምላካችን ፊት ቀንና ሌሊት የሚከሳቸው የወንድሞቻችን ከሳሽ ተጥሏልና።»

ሰይጣን ቢከሰንም እንኳ፣ በበጉ (በኢየሱስ) ደም ምክንያት ክሱ በእኛ ላይ ምንም ዓይነት ሕጋዊ ኃይል እንደሌለው አፅንዖት ሰጥተን ተመልክተናል (ራእይ 12:11)።

«እግዚአብሔር ሁሉን ቻይና ሉዓላዊ (Sovereign) ከሆነ ለምን መጸለይ አስፈለገን?» በሚለው ሐሳብ ላይ በጣም አስፈላጊ ውይይት ተነሥቶ ነበር። ከዘፍጥረት 1:26-28 እንደተረዳነው፣ እግዚአብሔር ለሰው ልጅ በምድር ላይ የመግዛትና የመሠልጠን ሕጋዊ ሥልጣን ሰጥቶታል። ጸሎት የእግዚአብሔርን ፈቃድ በምድር ላይ የምንለቅበት (የምናስፈጽምበት) መንገድ ነው። እግዚአብሔር በእኛ ጸሎት በኩል ለመሥራት መርጧል።

የጸሎት ዋናውና የመጨረሻው ግብ ከእግዚአብሔር ጋር ያለን የአባትና የልጅ ግንኙነት መሆኑም በብርቱ ተገልጧል — ጸሎት መልስ ማግኘት ብቻ ሳይሆን፣ ከእርሱ ጋር ባለን ቅርርብ ማደግ ነው። ልመናችን እኛ በጠበቅነው መንገድ ባይመለስ እንኳ፣ እግዚአብሔር አሁንም እግዚአብሔር ነው፤ ለእኛ የሚበጀውንም ያውቃል።

መጽሐፍ ቅዱስን ዝም ብለን እንደ ሃይማኖት መጽሐፍ ሳይሆን፣ የእግዚአብሔር መንግሥት በምድር ላይ እንዴት እንደሚሠራ የሚያሳይ የመንግሥቱ ሕገ-መንግሥት (Kingdom Constitution) አድርገን ስንመለከተው ትምህርቱ ይበልጥ የደመቀ ሆነ።

ሁሉም ሰው በደስታ ተሳትፏል፣ ስለ ጸሎት ያላቸውን ጥልቅ የግል ግንዛቤና ልምምድም አካፍለዋል። ውይይቱ እውነተኛ፣ የሚያበረታታ እና በመገለጥ የተሞላ ነበር። ብዙዎች ይህ ትምህርት ለጸሎት ያላቸውን አመለካከት እንዴት እንደለወጠው መስክረዋል።

<strong>የሚቀጥለው ሳምንት፦</strong>
በሚቀጥለው ቅዳሜ እንደገና ተገናኝተን ሌላኛውን ኃያል የመንግሥቱ መክፈቻ ለመቀጠል ተስማምተናል።

<strong>የሳምንቱ የማስታወሻ ጥቅስ፦</strong>
«ወደ እኔ ጩኽ፥ እኔም እመልስልሃለሁ፥ አንተም የማታውቀውን ታላቅና የተሸሸገውን ነገር አሳይሃለሁ።» (ኤርምያስ 33:3)

